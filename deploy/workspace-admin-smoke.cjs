const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const assert=require('node:assert/strict');

(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox']});
  const base=process.env.LOGICOV_ADMIN_TEST_URL || 'http://127.0.0.1:18302';
  const headers={'X-LogiCov-Request':'1'};
  const name=`Customer workspace ${Date.now()}`;
  const email=`workspace-${Date.now()}@example.test`;
  try {
    const page=await browser.newPage({viewport:{width:Number(process.env.LOGICOV_TEST_WIDTH || 1440),height:1000}});
    page.setDefaultTimeout(30000);
    page.on('dialog',dialog=>dialog.accept());
    await page.goto(base);
    await page.getByRole('button',{name:'Use a password instead',exact:true}).click();
    await page.locator('input[name=email]').fill('admin-smoke@example.test');
    await page.locator('input[name=password]').fill('Local-smoke-password-123!');
    await page.locator('input[name=password]').press('Enter');
    await page.getByRole('button',{name:'New Credit File',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Users',exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Workspaces',exact:true}).count(),0);
    await page.getByRole('button',{name:'Admin',exact:true}).click();
    await page.waitForURL('**/admin');
    await page.getByText('Administration',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'New Credit File',exact:true}).count(),0);
    await page.getByRole('button',{name:'Workspaces',exact:true}).click();
    await page.getByRole('textbox',{name:'Workspace name',exact:true}).fill(name);
    await page.getByRole('textbox',{name:'First administrator email',exact:true}).fill(email);
    await page.getByRole('button',{name:'Create workspace',exact:true}).click();
    await page.getByText('Workspace created. Open its users to invite the first administrator.',{exact:true}).waitFor();
    const workspace=(await (await page.request.get(base+'/api/admin/workspaces')).json()).find(w=>w.name===name);
    assert(workspace);assert.equal(workspace.administrators,1);
    await page.getByRole('button',{name:'Manage workspace users',exact:true}).click();
    await page.getByRole('button',{name:'Manage user',exact:true}).click();
    await page.getByRole('button',{name:'Send invitation',exact:true}).click();
    await page.getByText('Invitation accepted by the email provider. Inbox delivery is not yet confirmed.',{exact:true}).waitFor();
    const invitation=JSON.parse(await fs.readFile('target/email-smoke/message.json','utf8'));
    assert.equal(invitation.to,email);assert(invitation.text.includes(name));
    const member=await browser.newContext();
    assert.equal((await member.request.post(base+'/api/auth/email/request',{headers,data:{email}})).status(),200);
    const mail=JSON.parse(await fs.readFile('target/email-smoke/message.json','utf8'));
    const token=mail.text.match(/#signin=([A-Za-z0-9_-]+)/)[1];
    assert.equal((await member.request.post(base+'/api/auth/email/confirm',{headers,data:{email,token}})).status(),200);
    const session=await (await member.request.get(base+'/api/session')).json();
    assert.equal(session.tenantId,workspace.id);assert.equal(session.platformAdmin,false);
    assert.equal((await member.request.get(base+'/api/admin/workspaces')).status(),403);
    assert.equal((await member.request.post(base+'/api/admin/workspaces',{headers,data:{action:'Create',name:'Forbidden',administratorEmail:'forbidden@example.test'}})).status(),403);
    assert.equal((await member.request.get(base+`/api/admin/workspaces/${workspace.id}/users`)).status(),403);
    assert.equal((await (await member.request.get(base+'/api/admin/users')).json()).length,1);
    const overpostedEmail=`extra-${Date.now()}@example.test`;
    const overposted=await member.request.post(base+'/api/admin/users',{headers,data:{action:'Create',email:overpostedEmail,role:'Admin',platformAdmin:true}});
    assert.equal(overposted.status(),200);
    assert.equal((await overposted.json()).find(u=>u.email===overpostedEmail).platformAdmin,false);
    const memberPage=await member.newPage();memberPage.setDefaultTimeout(30000);await memberPage.goto(base);
    await memberPage.getByRole('button',{name:'New Credit File',exact:true}).waitFor();
    assert.equal(await memberPage.getByRole('button',{name:'Workspaces',exact:true}).count(),0);
    await memberPage.getByRole('button',{name:'New Credit File',exact:true}).click();
    await memberPage.locator('input[name=borrower]').fill('Customer isolation review');
    const chooser=memberPage.waitForEvent('filechooser');await memberPage.getByRole('button',{name:'Choose statement',exact:true}).click();
    await (await chooser).setFiles({name:'customer.csv',mimeType:'text/csv',buffer:Buffer.from('Revenue,120\nCash,10\n')});
    const saved=memberPage.waitForResponse(r=>r.url().endsWith('/api/deals')&&r.request().method()==='POST');
    await memberPage.getByRole('button',{name:'Ingest & Analyze',exact:true}).click();const deal=await (await saved).json();assert(deal.id);
    assert.equal((await page.request.get(base+'/api/deals/'+deal.id)).status(),404);
    assert.equal((await page.request.get(base+'/api/deals/'+deal.id+'/files/'+deal.documents[0].id)).status(),404);
    await page.getByRole('button',{name:'Back to workspace',exact:true}).click();
    await page.getByRole('textbox',{name:'Workspace name',exact:true}).fill(name+' renamed');
    await page.getByRole('button',{name:'Save workspace',exact:true}).click();
    await page.getByText('Workspace changes saved.',{exact:true}).waitFor();
    await page.getByRole('combobox',{name:'Workspace access',exact:true}).selectOption({label:'Suspended'});
    const suspended=page.waitForResponse(r=>r.url().endsWith('/api/admin/workspaces')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Save workspace',exact:true}).click();assert.equal((await suspended).status(),200);
    await page.getByText(/renamed · Suspended/).waitFor();
    assert.equal((await member.request.get(base+'/api/session')).status(),401);
    await page.getByRole('combobox',{name:'Workspace access',exact:true}).selectOption({label:'Active'});
    const reactivated=page.waitForResponse(r=>r.url().endsWith('/api/admin/workspaces')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Save workspace',exact:true}).click();assert.equal((await reactivated).status(),200);
    await page.getByText(/renamed · Active/).first().waitFor();
    assert.equal((await member.request.get(base+'/api/session')).status(),401);
    assert.equal((await page.request.post(base+'/api/admin/workspaces',{headers,data:{action:'Update',id:workspace.id,name,active:false,revision:1}})).status(),400);
    assert.equal((await page.request.post(base+'/api/admin/workspaces',{data:{action:'Create',name:'CSRF',administratorEmail:'csrf@example.test'}})).status(),403);
    if(process.env.LOGICOV_ADMIN_SCREENSHOT)await page.screenshot({path:process.env.LOGICOV_ADMIN_SCREENSHOT});
    await member.close();
    console.log('Workspace administration passed: create, invite, customer sign-in, admin isolation, customer data denial, rename, suspend/reactivate, permanent revocation, stale edit and CSRF denial');
  }finally{await browser.close();await fs.unlink('target/email-smoke/message.json').catch(error=>{if(error.code!=='ENOENT')throw error;});}
})().catch(error=>{console.error(error);process.exitCode=1;});
