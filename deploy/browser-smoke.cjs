const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(30000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.LOGICOV_TEST_URL||'http://127.0.0.1:18300';
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto(base);await page.getByLabel('Appearance',{exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.getByLabel('Appearance',{exact:true}).selectOption({label:'Light'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.reload();await page.getByLabel('Appearance',{exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.getByLabel('Appearance',{exact:true}).selectOption({label:'Device theme'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
  await page.locator('input[name=email]').fill(process.env.LOGICOV_TEST_EMAIL);
  await page.locator('input[name=password]').fill('incorrect-password');await page.locator('input[name=password]').press('Enter');
  await page.getByText('Email or password is incorrect.',{exact:true}).waitFor();
  await page.locator('input[name=password]').fill(process.env.LOGICOV_TEST_PASSWORD);await page.locator('input[name=password]').press('Enter');
  await page.getByRole('button',{name:'New Credit File',exact:true}).waitFor();await page.reload();
  await page.getByRole('button',{name:'New Credit File',exact:true}).click();
  const ingest=page.getByRole('button',{name:'Ingest & Analyze',exact:true});assert.equal(await ingest.getAttribute('aria-disabled'),'true');
  await page.locator('input[name=borrower]').fill('Browser Example');assert.equal(await ingest.getAttribute('aria-disabled'),'true');
  await page.getByRole('region',{name:'Statement upload'}).evaluate(el=>{const transfer=new DataTransfer();transfer.items.add(new File(['Account,2025\nRevenue,1200\nCash,50\nUnknown row,5\n'],'financials.csv',{type:'text/csv'}));el.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer}));});
  await page.getByLabel('Statement units',{exact:true}).selectOption({label:'USD thousands'});
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/deals')&&r.request().method()==='POST');await ingest.click();
  const deal=await(await saved).json();assert.equal(deal.grid.entity,'Browser Example');assert.equal(deal.grid.values.find(v=>v.item==='Revenue').value,1.2);assert(deal.issues.length>0);
  await page.getByText('Data Verification',{exact:true}).waitFor();
  await page.getByText('Revenue',{exact:true}).filter({visible:true}).first().click();
  await page.getByRole('textbox',{name:'Corrected amount (USD millions)',exact:true}).waitFor();
  await page.getByRole('textbox',{name:'Reason for correction',exact:true}).fill('Unsaved review');
  page.once('dialog',d=>d.dismiss());await page.getByRole('button',{name:'Back to deals',exact:true}).click();await page.getByText('Data Verification',{exact:true}).waitFor();
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Back to deals',exact:true}).click();await page.getByRole('button',{name:'New Credit File',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>localStorage.getItem('token')),null);assert.equal(await page.evaluate(()=>document.cookie.includes('logicov=')),false);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();await page.locator('input[name=password]').waitFor();
  assert.equal(await page.locator('input[name=password]').inputValue(),'');assert.deepEqual(errors,[]);
  console.log('Guided intake browser passed: login, reload, required fields, upload, units, cited data verification, dirty-edit protection and logout');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
