const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
  const base = 'http://127.0.0.1:18302';
  const email = 'email-smoke@example.test';
  const password = 'Reset-browser-password-123!';
  const headers = { 'X-LogiCov-Request': '1' };
  const capture = async () => JSON.parse(await fs.readFile('target/email-smoke/message.json', 'utf8'));
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(30000);
    await page.goto(base);
    await page.locator('input[name=email]').fill(email);
    await page.getByRole('button', { name: 'Email me a sign-in link', exact: true }).click();
    await page.getByText(/Delivery may take a few minutes/).waitFor();
    const resend = page.getByRole('button', { name: /^Resend in/ });
    await resend.waitFor();
    assert.equal(await resend.getAttribute('aria-disabled'), 'true');
    const mail = await capture();
    assert.equal(mail.to, email);
    assert.equal(mail['o:tracking'], 'no');
    const link = mail.text.match(/http:\/\/\S+/)[0];
    await page.goto(link);
    await page.getByRole('button', { name: 'Continue to workspace', exact: true }).waitFor();
    assert(!page.url().includes('#'));
    await page.locator('input[name=email]').fill('wrong@example.test');
    await page.getByRole('button', { name: 'Continue to workspace', exact: true }).click();
    await page.getByText(/This sign-in link is invalid or expired/).waitFor();
    await page.locator('input[name=email]').fill(email);
    await page.getByRole('button', { name: 'Continue to workspace', exact: true }).click();
    await page.getByRole('button', { name: 'New financial review', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.goto(link);
    await page.getByRole('button', { name: 'Continue to workspace', exact: true }).waitFor();
    await page.locator('input[name=email]').fill(email);
    await page.getByRole('button', { name: 'Continue to workspace', exact: true }).click();
    await page.getByText(/This sign-in link is invalid or expired/).waitFor();
    await page.getByRole('button', { name: 'Request a new link', exact: true }).click();
    await page.getByRole('button', { name: 'Forgot password?', exact: true }).click();
    await page.getByRole('button', { name: 'Email me a reset link', exact: true }).waitFor({ timeout: 75000 });
    await page.getByRole('button', { name: 'Email me a reset link', exact: true }).click();
    await page.getByText(/Delivery may take a few minutes/).waitFor();
    const resetMail = await capture();
    assert.equal(resetMail.subject, 'Reset your LogiCov password');
    const resetLink = resetMail.text.match(/http:\/\/\S+/)[0];
    const stale = await browser.newContext();
    assert.equal((await stale.request.post(base + '/api/auth/login', { headers, data: { email, password: process.env.LOGICOV_TEST_PASSWORD } })).status(), 200);
    await page.goto(resetLink);
    await page.getByRole('button', { name: 'Reset password', exact: true }).waitFor();
    await page.locator('input[name=email]').fill(email);
    await page.locator('input[type=password]').nth(0).fill(password);
    await page.locator('input[type=password]').nth(1).fill('Different-password-123!');
    await page.getByRole('button', { name: 'Reset password', exact: true }).click();
    await page.getByText('The passwords do not match.', { exact: true }).waitFor();
    await page.locator('input[type=password]').nth(1).fill(password);
    await page.getByRole('button', { name: 'Reset password', exact: true }).click();
    await page.getByText('Your password has been reset. Sign in with your new password.', { exact: true }).waitFor();
    assert.equal((await stale.request.get(base + '/api/session')).status(), 401);
    await page.locator('input[name=password]').fill(password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('button', { name: 'New financial review', exact: true }).waitFor();
    assert.equal((await page.request.post(base + '/api/auth/password/reset', { headers, data: { email, token: resetLink.split('#reset=')[1], password } })).status(), 401);
    console.log('Email browser passed: multipart delivery, cooldown, email binding, confirmation, replay denial, reset, session revocation and new-password login');
  } finally {
    await browser.close();
    await fs.unlink('target/email-smoke/message.json').catch(error => { if (error.code !== 'ENOENT') throw error; });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
